const { standardPage, loadClient } = require('./harness');
const page = standardPage();
loadClient({ document: page.document, localStorage: page.localStorage, body: `
  if (normalizeSession([]) !== null || normalizeSession('bad') !== null) throw Error('session shape');
  const normalized = normalizeSession({ baseline: null, humanCapture: { observedProperties: {} }, turns: [null] });
  if (normalized.baseline.skillLevel !== '' || normalized.humanCapture.observedProperties !== '') throw Error('nested shape');
  if (normalizeTemplates([null, 1, [], { id: '../bad', target: {} }]).length !== 1) throw Error('templates shape');
  let input;
  globalThis.FileReader = function () { this.readAsText = () => { this.result = JSON.stringify(input); this.onload(); }; };
  currentSession = normalizeSession({ id: 'original', target: 'Original' });
  templates = []; adaptationHistory = [];
  writeJson(STORAGE_KEYS.session, currentSession);
  const before = localStorage.getItem(STORAGE_KEYS.session);
  input = null;
  await importData({}).then(() => { throw Error('null accepted'); }, error => { if (!error.message.includes('backup')) throw error; });
  input = { app: 'mas-backup', session: { target: 'Replacement' }, templates: [], history: [] };
  const originalSet = localStorage.setItem;
  let failed = false;
  localStorage.setItem = (key, value) => {
    if (key === STORAGE_KEYS.templates && !failed) { failed = true; throw Error('quota'); }
    originalSet(key, value);
  };
  await importData({}).then(() => { throw Error('quota accepted'); }, error => { if (!error.message.includes('quota')) throw error; });
  localStorage.setItem = originalSet;
  if (localStorage.getItem(STORAGE_KEYS.session) !== before || currentSession.target !== 'Original') throw Error('rollback lost data');
  input = { app: 'mas-backup', session: null, templates: [], history: [] };
  await importData({});
  if (currentSession !== null) throw Error('explicit clear ignored');
  await importData({ size: 21 * 1024 * 1024 }).then(() => { throw Error('oversize accepted'); }, () => {});
  if (normalizeHistory([null, 7, [], { note: {}, target: {} }]).length !== 1) throw Error('history shape');
  currentSession = normalizeSession({ target: 'Score validation' });
  adaptationHistory = [];
  logCheckIn();
  if (adaptationHistory.length) throw Error('blank scores recorded as zero');
  for (const selector of ['#ci-quality', '#ci-effort', '#ci-stability']) document.querySelector(selector).value = '5';
  document.querySelector('#ci-discomfort').value = '0';
  document.querySelector('#ci-note').value = 'retain my draft';
  localStorage.setItem = () => { throw Error('quota'); };
  logCheckIn();
  if (adaptationHistory.length || document.querySelector('#ci-note').value !== 'retain my draft') throw Error('failed check-in lost draft');
  localStorage.setItem = originalSet;
  logCheckIn();
  if (adaptationHistory.length !== 1 || adaptationHistory[0].discomfort !== 0) throw Error('valid zero discomfort rejected');
  currentSession = normalizeSession({ target: 'quota draft' });
  localStorage.setItem = () => { throw Error('quota'); };
  if (saveSession() !== false || !sessionSaveFailed || currentSession.target !== 'quota draft') throw Error('session quota lost draft');
  renderSession();
  if (!document.querySelector('#capture-save-status').textContent.includes('Not saved')) throw Error('false saved badge');
  localStorage.setItem = originalSet;
  if (!saveSession() || sessionSaveFailed) throw Error('session quota recovery');
  await refreshApiStatus();
  const attempts = apiPollFailures;
  await refreshApiStatus();
  if (apiPollFailures !== attempts) throw Error('offline polling ignored backoff');
  console.log('  reliability: normalization, quota rollback, explicit clear, backup size and check-in validation OK');
` });
