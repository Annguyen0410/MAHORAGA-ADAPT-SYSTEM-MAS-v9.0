const { standardPage, loadClient } = require('./harness');
const handlers = {};
const page = standardPage({ localStorage: { 'mas.currentSession.v2': 'null', 'mas.currentSession.v1': JSON.stringify({ target: 'Old session must not revive' }) } });
const originalQuery = page.document.querySelector;
page.document.querySelector = selector => {
  const element = originalQuery(selector);
  element.addEventListener = (event, handler) => { handlers[selector + '/' + event] = handler; };
  return element;
};
loadClient({ document: page.document, localStorage: page.localStorage, windowExtras: { handlers }, body: `
  globalThis.alert = () => {};
  globalThis.confirm = () => true;
  if (currentSession !== null) throw Error('explicit clear revived legacy session');
  const originalPost = apiPost;
  let finish;
  apiPost = () => new Promise(resolve => { finish = resolve; });
  apiAvailable = true;
  rateLimitInfo.remaining = 20;
  currentSession = normalizeSession({ id: 'owner', target: 'Original', humanCapture: { observedProperties: 'observed' } });
  const generating = window.handlers['#generate-full/click']();
  currentSession = null;
  finish({ ok: true, data: { assessment: {} } });
  await generating;
  if (currentSession !== null) throw Error('late assessment repopulated deleted session');
  currentSession = normalizeSession({ id: 'owner', target: 'Original', humanCapture: { observedProperties: 'observed' } });
  geminiAvailable = true;
  const diving = window.handlers['#run-deep-analysis/click']();
  currentSession = normalizeSession({ target: 'Replacement' });
  finish({ ok: true, data: { perspectives: [] } });
  await diving;
  if (currentSession.deepAnalysis !== null) throw Error('late deep analysis reached replacement session');
  currentSession = null;
  document.querySelector('#target-name').value = 'New target';
  saveSessionTarget();
  currentSession = null;
  finish({ ok: true, data: { id: 'server-late' } });
  await Promise.resolve();
  if (currentSession !== null) throw Error('late create revived cleared session');
  apiPost = originalPost;
  currentSession = normalizeSession({ target: 'quota', roadmap: 'retained' });
  document.querySelector('#roadmap-editor').value = 'retained';
  const originalSet = localStorage.setItem;
  localStorage.setItem = () => { throw Error('quota'); };
  window.handlers['#clear-session/click']();
  if (!currentSession) throw Error('failed clear discarded session');
  templates = [ { id: 'keep', target: 'Retain template' } ];
  window.handlers['#clear-templates/click']();
  if (templates.length !== 1) throw Error('failed clear discarded templates');
  window.handlers['#save-roadmap-template/click']();
  if (templates.length !== 1) throw Error('failed template save updated memory');
  localStorage.setItem = originalSet;
  _saveTimers.capture = setTimeout(() => { throw Error('cleared session debounce still ran'); }, 500);
  window.handlers['#clear-session/click']();
  if (currentSession !== null || Object.keys(_saveTimers).length) throw Error('clear did not cancel autosave');
  console.log('  lifecycle: late create/assessment/deep replies, quota actions and clear timers OK');
` });
