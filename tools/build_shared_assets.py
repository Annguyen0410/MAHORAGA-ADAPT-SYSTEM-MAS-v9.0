"""Build cross-platform assets; never reads profiles, keys or server data."""
import json
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]


def main():
    manifest = json.loads((ROOT / "litebrowser/data/chain.json").read_text(encoding="utf-8"))
    web = ROOT / "web_support"
    local_ids = [app["id"] for app in manifest["apps"] if (web / app["folder"] / "index.html").is_file()]
    template = r'''// Generated by tools/build_shared_assets.py from litebrowser/data/chain.json.
(function () {
  "use strict";
  var EMBEDDED = __MANIFEST__;
  var LOCAL_IDS = __LOCAL_IDS__;
  var isLocal = location.protocol === "file:";
  var source = document.currentScript && document.currentScript.src || new URL("chain.js", location.href).href;
  var sharedRoot = new URL(__ROOT__, source);
  function localUrl(app) { return new URL(encodeURIComponent(app.folder || app.id) + "/index.html", sharedRoot).href; }
  function build(data) {
    var apps = Array.isArray(data.apps) ? data.apps : [];
    var chain = { name: data.chainName || data.name || "Project Chain", mode: isLocal ? "local" : "remote", isLocal: isLocal };
    chain.apps = apps.filter(function (app) {
      return app && typeof app.id === "string" && /^[a-z0-9_-]+$/.test(app.id) && typeof app.folder === "string" && !/[\\/:]/.test(app.folder) && app.folder !== ".." && (!app.remote || /^https?:\/\//.test(app.remote));
    }).map(function (app) {
      var remote = typeof app.remote === "string" ? app.remote.replace(/\/+$/, "") : "";
      return Object.assign({}, app, { local: localUrl(app), remote: remote,
        url: (!isLocal && remote || LOCAL_IDS.indexOf(app.id) < 0 && remote) || localUrl(app) });
    });
    chain.appsById = Object.create(null);
    chain.apps.forEach(function (app) { chain.appsById[app.id] = app; });
    chain.url = function (id) { return chain.appsById[id] ? chain.appsById[id].url : ""; };
    chain.app = function (id) { return chain.appsById[id] || null; };
    chain.hubUrl = chain.url("hub");
    chain.manifestUrl = new URL("chain.json", source).href;
    return chain;
  }
  var CHAIN = window.CHAIN = build(EMBEDDED);
  function applyLinks() {
    document.querySelectorAll("[data-chain-link]").forEach(function (element) {
      var app = CHAIN.app(element.getAttribute("data-chain-link"));
      if (!app) return;
      element.setAttribute("href", app.url);
      if (element.hasAttribute("data-chain-text")) element.textContent = element.getAttribute("data-chain-text").replace("{name}", app.name);
    });
    document.dispatchEvent(new CustomEvent("chain:ready", { detail: CHAIN }));
  }
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", applyLinks); else applyLinks();
  if (!isLocal) fetch(CHAIN.manifestUrl, { cache: "no-store" }).then(function (response) { return response.ok ? response.json() : null; }).then(function (data) {
    if (!data || !Array.isArray(data.apps)) return;
    window.CHAIN = CHAIN = build(data); applyLinks();
  }).catch(function () {});
})();
'''
    mirrors = [web, *[path.parent for path in web.glob("*/chain.js")]]
    payload = json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"
    for directory in mirrors:
        (directory / "chain.json").write_text(payload, encoding="utf-8")
        script = template.replace("__MANIFEST__", payload.strip()).replace("__LOCAL_IDS__", json.dumps(local_ids))
        script = script.replace("__ROOT__", json.dumps("./" if directory == web else "../"))
        (directory / "chain.js").write_text(script, encoding="utf-8")
    extension = ROOT / "Extensions/tab-window-bridge"
    archive_path = ROOT / "Extensions/MeiBridge-extension.zip"
    temporary = archive_path.with_suffix(".zip.tmp")
    try:
        with zipfile.ZipFile(temporary, "w", zipfile.ZIP_DEFLATED) as archive:
            for path in sorted(extension.rglob("*")):
                if not path.is_file() or path.suffix == ".zip" or any(part.startswith(".") for part in path.relative_to(extension).parts):
                    continue
                info = zipfile.ZipInfo(path.relative_to(extension).as_posix(), (2026, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = 0o644 << 16
                archive.writestr(info, path.read_bytes())
        temporary.replace(archive_path)
    finally:
        temporary.unlink(missing_ok=True)
    print(f"Built {len(mirrors)} chain mirrors and extension archive")


if __name__ == "__main__":
    main()
